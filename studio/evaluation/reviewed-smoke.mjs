// Technical-only integration fixture. No external Commons image is used.
import { mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { stageReviewedAssets } from '../assets/stage-reviewed.mjs';
const dir='reviewed-smoke-output';
await rm(dir,{recursive:true,force:true});
await mkdir(dir,{recursive:true});
const pictures=[];
for(let i=0;i<2;i++){
 const filename=dir+'/fixture-'+(i+1)+'.png';
 execFileSync('ffmpeg',['-nostdin','-hide_banner','-loglevel','error','-y',
   '-f','lavfi','-i','color=c='+(i?'purple':'navy')+':s=480x360','-frames:v','1',filename]);
 pictures.push(await readFile(filename));
}
const captions=['猫が眠っています。','猫は目を覚ましました。'];
const scenes=captions.map((narration,i)=>({narration,search_query:'synthetic test image '+i}));
const sourcePage=i=>'https://commons.wikimedia.org/wiki/File:Shorts_CI_Fixture_'+(i+1)+'.png';
const imageUrl=i=>'https://upload.wikimedia.org/wikipedia/commons/f/fi/Shorts_CI_Fixture_'+(i+1)+'.png';
const discovery={scenes:scenes.map((s,i)=>({sceneIndex:i,sceneId:'test-'+(i+1),narration:s.narration,candidates:[{
 imageUrl:imageUrl(i),sourcePage:sourcePage(i),creator:'Generated by test code',
 license:'CC0',licenseUrl:'https://creativecommons.org/publicdomain/zero/1.0/',
 rightsStatus:'needs-human-license-review'
}]}))};
const selections=scenes.map((_,i)=>({sceneIndex:i,imageUrl:imageUrl(i),sourcePage:sourcePage(i),
 rightsReviewed:true,visualMatchesNarration:true,humanApproved:true,
 credit:'Generated by test code, no Commons image fetched',
 licenseSnapshot:'SYNTHETIC CI FIXTURE; NOT A REAL EXTERNAL LICENSE'}));
let index=0;
await stageReviewedAssets(discovery,selections,dir+'/approved',{
 download:async()=>pictures[index++]
});
const script={topic:'SYNTHETIC TECHNICAL TEST',scenes};
const timing={durationMs:2400,timingSource:'synthetic-tone-is-not-speech',
 scenes:[{startMs:0,endMs:1200},{startMs:1200,endMs:2400}],
 cues:[{startMs:0,endMs:1180,text:captions[0]},{startMs:1200,endMs:2380,text:captions[1]}]};
await writeFile(dir+'/script.json',JSON.stringify(script));
await writeFile(dir+'/timing.json',JSON.stringify(timing));
execFileSync('ffmpeg',['-nostdin','-hide_banner','-loglevel','error','-y',
 '-f','lavfi','-i','sine=frequency=440:duration=2.4','-ac','1','-ar','24000',dir+'/synthetic.wav']);
execFileSync('python3',['studio/voice/render_reviewed.py','--script',dir+'/script.json',
 '--timing',dir+'/timing.json','--images',dir+'/approved',
 '--audio',dir+'/synthetic.wav','--out',dir+'/result']);
const report=JSON.parse(await readFile(dir+'/result/render-report.json','utf8'));
if(report.qualityApproved!==false||Math.abs(report.seconds-2.4)>0.4)
 throw Error('Technical preview report invalid');
console.log('Technical synthetic MP4 ready. Not a completed Shorts video.');
